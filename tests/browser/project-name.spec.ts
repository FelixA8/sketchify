import { test, expect } from '@playwright/test';
import { seedStorage } from './storage';

for (const width of [375, 820, 1440]) for (const theme of ['light', 'dark']) test(`project name editing fits and persists at ${width}px in ${theme}`, async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width, height: 900 });
  await seedStorage(page, { elements: [], local: { theme, iconTextSize: 'large' } });
  await page.goto('/');
  const label = page.locator('#project-name-button'), input = page.getByRole('textbox', { name: 'Project name', exact: true });
  await expect(label).toBeVisible(); await expect(label).toHaveText('Sketchify');
  await expect(page.locator('#save-state')).toHaveText('Saved on this device');
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('sketchify.scene.v1')!).local.name);
  expect(original).toMatch(/^sketchify_\d{4}-\d{2}-\d{2}$/);
  await label.click(); await expect(input).toBeFocused(); await expect(input).toHaveValue('Sketchify');
  expect(await input.evaluate((node: HTMLInputElement) => [node.selectionStart, node.selectionEnd])).toEqual([0, 9]);
  await input.press('Enter');
  await expect(label).toBeFocused();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('sketchify.scene.v1')!).local.name)).toBe(original);
  await label.press('Enter'); await expect(input).toBeFocused(); await input.fill('WealthSync'); await input.press('Enter');
  await expect(label).toHaveText('WealthSync');
  await expect(page.locator('#save-state')).toHaveText('Saved on this device');
  await page.reload(); await expect(label).toHaveText('WealthSync');
  await label.click(); await input.fill('Discard'); await input.press('Escape'); await expect(label).toHaveText('WealthSync');
  await label.press('Space'); await expect(input).toBeFocused(); await input.fill('A long project name '.repeat(5));
  const field = (await input.boundingBox())!, menu = (await page.locator('#menu-button').boundingBox())!;
  expect(field.x).toBeGreaterThanOrEqual(menu.x + menu.width);
  expect(field.x + field.width).toBeLessThanOrEqual(width);
  if (width > 760) expect(field.x + field.width).toBeLessThan((await page.locator('#toolbar').boundingBox())!.x);
  else expect(field.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({ path: `artifacts/project-name-${width}-${theme}-editing.png` });
  await page.locator('#canvas').click({ position: { x: 10, y: 400 } });
  await expect(input).toBeHidden();
  await expect(page.locator('#save-state')).toHaveText('Saved on this device');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);
  await label.press('Enter'); await input.fill('Final project'); await input.press('Tab'); await expect(label).toHaveText('Final project');
  await expect(page.locator('#save-state')).toHaveText('Saved on this device');
  await page.locator('#canvas').focus();
  const download = page.waitForEvent('download'); await page.keyboard.press('ControlOrMeta+s');
  expect((await download).suggestedFilename()).toBe('Final project.sketchify');
  expect(errors).toEqual([]);
});
